import re
def replace_adj_case(text, num, endings):
    # объединяем окончания из списка в одну строку
    endings_pattern = '|'.join(endings)
    # Отдельное слово, состоящее из русских букв,но исключает слова заканчивающие на определенную букву, и заканчиваются на определенное окончание
    adjective_pattern = rf'\b([А-Яа-яЁё]+?)(?<![здлетик])({endings_pattern})\b'
    adjectives = re.findall(adjective_pattern, text) #ищем прилагательное

    if not adjectives:
        return "Прилагательных не найдено."
    # Проверяем находится ли введенный номер прилагательных в нашем диапозоне
    if num > len(adjectives) or num <= 0:
        return "Номер прилагательно вне диапазона"

    chosen_adj_stem = adjectives[num - 1][0].lower() # Приводим к строчным буквам и сохраняем первую часть (без окончания)
    chosen_adj_ending = adjectives[num - 1][1] # Сохраняем вторую часть (окончания) Приведения нет, потому что окончания всегда строчные

    # Функция для замены окончания
    def replace_with_new_ending(match):
        adj_stem = match.group(1) #извлекаем корень
        # adj_ending = match.group(2) #извлекаем окончание
        # Если корень совпадает, то заменяем окончание
        if adj_stem.lower() == chosen_adj_stem:
            return adj_stem + chosen_adj_ending
        return match.group(0)

    result = re.sub(adjective_pattern, replace_with_new_ending, text)

    return result


